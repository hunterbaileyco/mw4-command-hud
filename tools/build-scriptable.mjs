#!/usr/bin/env node
// Assemble the single-file Scriptable scripts (Scriptable can't import local modules on a fresh phone):
//   header + tools/mw4crypto.js + scriptable/src/common.js + scriptable/src/<body>.js -> scriptable/<Name>.js
// Also writes the two paste-once loaders. Those files only download the built scripts from GitHub Raw.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const rd = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const crypto = rd('tools/mw4crypto.js'), common = rd('scriptable/src/common.js');
const INSTALL = (name, sizes, what) => {
  const short = name.replace('MW4 ', '');
  return `/*
 * ${name} — Scriptable widget (${sizes}). ${what}
 *
 * PHONE: do not paste this file. Paste scriptable/${name} Loader.js once, over the
 * existing "${short}" script, and keep the name "${short}" so the Home Screen widget
 * stays attached. The loader downloads this file from GitHub Raw on every run.
 * Edit scriptable/src/*, run node tools/build-scriptable.mjs, merge to main.
 * No re-paste. Run the loader once in the app if the widget says AUTH NEEDED.
 *
 * AUTH CODE is checked, then saved in the iOS Keychain (Keychain.set "mw4hud.authcode").
 * New auth code? Set RESET = true below, rebuild, merge, run the loader once, enter the
 * new code, set RESET back to false, rebuild, merge.
 *
 * HOW IT WORKS: status.json is encrypted (AES-256-GCM, key = PBKDF2-SHA256(auth code, salt, iter)).
 * Scriptable has no Web Crypto, so a small pure-JS PBKDF2 + AES-GCM (MW4C below) decrypts on the phone.
 * The derived key is cached in the Keychain ("mw4hud.aeskey") so widget refreshes skip the PBKDF2 work.
 * Only the encrypted feed is cached on disk for offline use. iOS refreshes widgets roughly every 15–30 min.
 * Generated by tools/build-scriptable.mjs — edit scriptable/src/*, then rebuild.
 */
`;
};
const targets = [
  ['MW4 Glance', 'glance.body.js', 'deep-brown', 'crosshairs', 'small / medium', 'Theater HUD: ACT/HOLD/QUEUE/SHIPPED chrome, AO plates, the wire, HOLD, AAR ticker.'],
  ['MW4 Waiting', 'waiting.body.js', 'yellow', 'exclamation-triangle', 'small / medium / large', 'HOLD cage: "Waiting on Hunter" cards (Command, then Kal) under a hazard rail.'],
];

// Same acceptance rule the loaders use. A GitHub error page or a 404 body must not replace the cache.
function sourceOk(source, marker) {
  return typeof source === 'string'
    && source.length > 1000
    && source.includes(marker)
    && source.includes('Script.setWidget')
    && !source.includes('<html')
    && !source.includes('<!DOCTYPE');
}

function loaderSource(name, color, glyph) {
  const short = name.replace('MW4 ', '');
  const url = 'https://raw.githubusercontent.com/hunterbaileyco/mw4-command-hud/main/scriptable/' + encodeURIComponent(name + '.js');
  const cache = 'mw4-' + short.toLowerCase() + '-script.js';
  const marker = name + ' — Scriptable';
  const title = name.toUpperCase();
  return `// Variables used by Scriptable.
// These must be at the very top of the file. Do not edit.
// icon-color: ${color}; icon-glyph: ${glyph};

/*
 * ${name} Loader — paste this into Scriptable once.
 *
 * Replace the existing "${short}" script with this file and keep the name ${short}.
 * The Home Screen widget stays pointed at it. If that script is gone, add a new
 * one, name it ${short}, and select it on the widget.
 *
 * Every run downloads the latest full ${short} widget from GitHub (main) and runs
 * it. The last copy that compiled is kept on this phone. A failed download runs
 * that copy. With no copy yet, the widget shows NO SCRIPT.
 *
 * Ship widget changes by merging them to main. Do not paste the full script again.
 * This file does not download the status feed — the script it runs does.
 * Tap ▶ once if the widget says AUTH NEEDED. The HUD code stays in the iOS Keychain.
 */

const SCRIPT_URL = ${JSON.stringify(url)};
const CACHE_NAME = ${JSON.stringify(cache)};
const MARKER = ${JSON.stringify(marker)};
const TITLE = ${JSON.stringify(title)};

// Local documents persists and is shared with the widget extension.
// cacheDirectory is not shared with the widget and iOS may delete it.
// iCloud documents is the scripts folder and can stall a refresh while downloading.
function cacheFile() {
  const fm = FileManager.local();
  return { fm, path: fm.joinPath(fm.documentsDirectory(), CACHE_NAME) };
}

function stripBom(source) {
  if (source && source.charCodeAt(0) === 0xFEFF) return source.slice(1);
  return source;
}

function readCache() {
  const { fm, path } = cacheFile();
  try {
    if (fm.fileExists(path)) return stripBom(fm.readString(path));
  } catch (e) {}
  return null;
}

function writeCache(source) {
  const { fm, path } = cacheFile();
  fm.writeString(path, source);
}

function sourceOk(source) {
  return typeof source === "string"
    && source.length > 1000
    && source.indexOf(MARKER) !== -1
    && source.indexOf("Script.setWidget") !== -1
    && source.indexOf("<html") === -1
    && source.indexOf("<!DOCTYPE") === -1;
}

// The built widget uses top-level await. That is legal in the main Scriptable
// script and inside an async function. A plain Function/eval body rejects it.
const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;

function compile(source) {
  return new AsyncFunction(source);
}

function usable(source) {
  if (!sourceOk(source)) return false;
  try { compile(source); return true; } catch (e) { return false; }
}

async function fetchLatest(seconds) {
  const req = new Request(SCRIPT_URL + "?t=" + Date.now());
  req.timeoutInterval = seconds;
  req.headers = { "User-Agent": "Scriptable MW4 Loader", "Accept": "text/plain" };
  const source = stripBom(await req.loadString());
  if (!sourceOk(source)) throw new Error("unexpected script");
  return source;
}

async function resolveSource() {
  const cached = readCache();
  const cachedOk = usable(cached);
  // When a copy is already runnable, cap the download so a slow GitHub call
  // still leaves time for the widget's own encrypted-feed request.
  try {
    const fresh = await fetchLatest(cachedOk ? 4 : 8);
    if (!usable(fresh)) throw new Error("script did not compile");
    try { writeCache(fresh); } catch (e) {}
    return fresh;
  } catch (e) {
    return cachedOk ? cached : null;
  }
}

async function showError(detail) {
  const w = new ListWidget();
  w.backgroundColor = new Color("#0B0E0C");
  w.setPadding(12, 12, 12, 12);
  const title = w.addText(TITLE);
  title.font = Font.heavyMonospacedSystemFont(12);
  title.textColor = new Color("#C5A572");
  title.lineLimit = 1;
  w.addSpacer(4);
  const line = w.addText(detail);
  line.font = Font.mediumMonospacedSystemFont(11);
  line.textColor = new Color("#E07A5F");
  line.lineLimit = 3;
  w.refreshAfterDate = new Date(Date.now() + 5 * 60 * 1000);
  if (config.runsInWidget) Script.setWidget(w);
  else {
    try { await w.presentSmall(); } catch (e) {}
  }
  Script.complete();
}

const source = await resolveSource();
if (!source) {
  await showError("NO SCRIPT\\nRun once online");
} else {
  try {
    await compile(source)();
  } catch (e) {
    await showError("SCRIPT ERROR");
  }
}
`;
}

for (const [name, body, color, glyph, sizes, what] of targets) {
  const out = `// Variables used by Scriptable.\n// These must be at the very top of the file. Do not edit.\n// icon-color: ${color}; icon-glyph: ${glyph};\n` +
    INSTALL(name, sizes, what) + '\n' + common + '\n' + crypto + '\n// ===== widget =====\n' + rd('scriptable/src/' + body);
  fs.writeFileSync(path.join(root, 'scriptable', name + '.js'), out);
  const loader = loaderSource(name, color, glyph);
  fs.writeFileSync(path.join(root, 'scriptable', name + ' Loader.js'), loader);
  console.log('wrote scriptable/' + name + '.js', out.length, 'bytes');
  console.log('wrote scriptable/' + name + ' Loader.js', loader.length, 'bytes');
}

const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;
const statusLine = common.split('\n').find((line) => line.startsWith('const STATUS_URL'));
if (!statusLine || !statusLine.includes('https://mw4-command-hud.vercel.app/') || !statusLine.includes('x-vercel-protection-bypass=')) {
  throw new Error('STATUS_URL must stay the Vercel encrypted feed plus the bypass query');
}
for (const [name, , color, glyph] of targets) {
  const marker = name + ' — Scriptable';
  const widget = rd('scriptable/' + name + '.js');
  const loader = rd('scriptable/' + name + ' Loader.js');
  const lines = loader.split('\n').length;
  if (!widget.includes(statusLine)) throw new Error(name + ' dropped STATUS_URL');
  if (!sourceOk(widget, marker)) throw new Error(name + ' would be rejected by its loader');
  if (sourceOk('404: Not Found', marker)) throw new Error('loader would cache a 404');
  if (sourceOk('<!DOCTYPE html><html>' + marker + 'Script.setWidget' + 'x'.repeat(1100), marker)) {
    throw new Error('loader would cache an HTML error page');
  }
  new AsyncFunction(widget);
  new AsyncFunction(loader);
  if (!loader.startsWith('// Variables used by Scriptable.\n// These must be at the very top of the file. Do not edit.\n// icon-color: ' + color + '; icon-glyph: ' + glyph + ';\n')) {
    throw new Error(name + ' loader icon header is not at the top');
  }
  if (!loader.includes(encodeURIComponent(name + '.js'))) throw new Error(name + ' loader is missing its raw URL');
  if (!loader.includes(marker)) throw new Error(name + ' loader is missing its marker');
  if (loader.includes('x-vercel-protection-bypass') || loader.includes('mw4-command-hud.vercel.app') || loader.includes('AUTH_HASH')) {
    throw new Error(name + ' loader must only fetch script source, not the feed');
  }
  if (lines > 180) throw new Error(name + ' loader is ' + lines + ' lines');
  console.log('checked', name, 'loader', lines, 'lines');
}
